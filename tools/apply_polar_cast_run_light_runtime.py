#!/usr/bin/env python3
"""Wire the compact receiver-owned Polar cast-plane bake into the GG runtime.

This replaces the old runtime shadow-polygon experiment with the intended Polar
shape: four static cast planes, treated as virtual wall-bottom edges.  The Z80
never constructs, clips, or scan-fills world polygons here.

For the two-room validation scene the receiver ownership gate is especially
cheap: Room A light is only valid beyond the x=80 portal plane, Room B beyond
x=112.  Those two gate planes are existing authored surface bounds.  The
runtime therefore intersects three cheap half-planes per receiver:
  Room A: cast from v2, cast from v3, x<=80 receiver gate
  Room B: cast from v6, cast from v7, x>=112 receiver gate

Each plane has a screen inverse-depth recurrence exactly like an arbitrary
straight Polar wall.  The two cast normal/yaw terms are PC-baked; the two
cardinal receiver gates get equally baked 256-entry terms in this patch.

The lighting translation unit is separately BANKED.  It writes only the
20x18 authoritative WRAM name-table shadow, marks existing coverage/dirty
state, and lets the mature VBlank uploader perform the actual VDP writes.
"""
from pathlib import Path
import re

BRANCH_NOTE = "POLAR_CAST_RUN_RUNTIME_PATCH=APPLIED"


def replace_once(text: str, old: str, new: str, label: str) -> str:
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"{label}: expected exactly one anchor, found {n}")
    return text.replace(old, new, 1)


def generated_c_array(name: str, renamed: str) -> str:
    data = "\n".join(p.read_text() for p in sorted(Path("src/generated").glob("tilesector_polar_data_part*.inc")))
    pat = re.compile(r"static\s+const\s+[^;{]+?\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{.*?\};", re.S)
    m = pat.search(data)
    if not m:
        raise SystemExit(f"generated array not found: {name}")
    return m.group(0).replace(name, renamed, 1)


def generated_int_array(name: str):
    data = "\n".join(p.read_text() for p in sorted(Path("src/generated").glob("tilesector_polar_data_part*.inc")))
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", data, re.S)
    if not m:
        raise SystemExit(f"generated integer array not found: {name}")
    return [int(x) for x in re.findall(r"-?\d+", m.group(1))]


def c_i8(name: str, vals, cols=16) -> str:
    out=[f"static const int8_t {name}[{len(vals)}] = {{"]
    for i in range(0,len(vals),cols): out.append("    "+", ".join(str(int(v)) for v in vals[i:i+cols])+",")
    out.append("};")
    return "\n".join(out)


