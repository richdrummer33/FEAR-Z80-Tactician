; Shared exact 8x8 -> 16 multiply for the banked envelope depth evaluators.
; SDCC's generated quarter-square helper builds an IX frame for every multiply;
; the depth path does four multiplies per visible run.  Keep the same exact
; quarter-square identity in fixed ROM, but do it in straight Z80.
;
; ABI used by SDCC/GBDK here: A=a, L=b, return uint16_t in DE.
_e1env_mul8u::
        ld      c, a                    ; preserve a
        ld      b, l                    ; preserve b

        sub     b                       ; signed a-b
        jr      nc, e1mul_diff_ready$
        neg
e1mul_diff_ready$:
        push    af                      ; stash |a-b|

        ld      a, c
        add     a, b                    ; low byte of a+b, carry is bit 8
        ld      l, a
        ld      h, #0
        jr      nc, e1mul_sum_ready$
        inc     h
e1mul_sum_ready$:
        add     hl, hl                  ; uint16 table byte offset
        ld      de, #e1env_qsquare$
        add     hl, de
        ld      e, (hl)
        inc     hl
        ld      d, (hl)                 ; DE = Q[a+b]

        pop     af                      ; A = |a-b|
        ld      c, e
        ld      b, d                    ; BC = Q[a+b]
        ld      l, a
        ld      h, #0
        add     hl, hl
        ld      de, #e1env_qsquare$
        add     hl, de
        ld      e, (hl)
        inc     hl
        ld      d, (hl)                 ; DE = Q[|a-b|]

        ld      a, c
        sub     e
        ld      e, a
        ld      a, b
        sbc     a, d
        ld      d, a                    ; DE = exact a*b
        ret

