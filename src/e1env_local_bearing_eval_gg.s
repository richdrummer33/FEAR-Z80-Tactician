; Evaluate one four-byte descriptor already copied into WRAM:
;   [base_lo, packed, sx_s8, sy_s8]
;
; packed low nibble  = base bits 8..11
; packed high nibble = signed 4-bit bilinear coefficient sxy [-8,7]
;
; Normal affine records have sxy=0 and pay only one cheap branch. Rescue
; records add:
;   trunc(trunc(sxy*lx/16)*ly/16)
; which is exactly the arithmetic exhaustively validated by the baker.
;
; bearing = base + trunc(sx*lx/16) + trunc(sy*ly/16) + cross, modulo 4096.
_e1env_local_bearing_eval::
        push    bc
        push    de
        push    hl

        ld      hl, (#_g_e1env_lbf_ptr)
        ld      e, (hl)                 ; base low
        inc     hl
        ld      a, (hl)                 ; packed base high + signed sxy nibble
        ld      b, a                    ; retain packed byte through affine work
        and     #0x0f
        ld      d, a
        ld      (#lbf_base$), de
        inc     hl
        ld      a, (hl)
        ld      (#lbf_slope$), a
        inc     hl
        ld      a, (hl)
        ld      (#lbf_sy$), a

        ; A common movement rail lands exactly on a world-cell Y boundary.
        ; For ly=0 the Y term and bilinear cross term are mathematically zero,
        ; so evaluate only X instead of paying the second multiply plus all
        ; cross-term bookkeeping for every visible boundary vertex.
        ld      a, (#_g_e1env_lbf_ly)
        or      a
        jr      nz, lbf_general$
        ld      a, (#_g_e1env_lbf_lx)
        or      a
        jr      z, lbf_ly0_base$
        ld      c, a
        ld      a, (#lbf_slope$)
        call    lbf_mul_s8_u4_div16$
        ld      e, a
        ld      d, #0
        bit     7, e
        jr      z, lbf_ly0_x_pos$
        dec     d
lbf_ly0_x_pos$:
        ld      hl, (#lbf_base$)
        add     hl, de
        jp      lbf_finalize$
lbf_ly0_base$:
        ld      hl, (#lbf_base$)
        jp      lbf_finalize$

lbf_general$:
        ld      a, (#_g_e1env_lbf_lx)
        ld      c, a
        ld      a, (#lbf_slope$)
        call    lbf_mul_s8_u4_div16$
        ld      (#lbf_corrx$), a

        ld      a, (#_g_e1env_lbf_ly)
        ld      c, a
        ld      a, (#lbf_sy$)
        call    lbf_mul_s8_u4_div16$
        ld      c, a

        ld      hl, (#lbf_base$)

        ; Add signed Y correction.
        ld      e, c
        ld      d, #0
        bit     7, e
        jr      z, lbf_y_pos$
        dec     d
lbf_y_pos$:
        add     hl, de

        ; Add signed X correction.
        ld      a, (#lbf_corrx$)
        ld      e, a
        ld      d, #0
        bit     7, e
        jr      z, lbf_x_pos$
        dec     d
lbf_x_pos$:
        add     hl, de

        ; High nibble zero is the overwhelmingly common affine path. Keep the
        ; old hot path intact apart from this test. For rescue records decode
        ; the signed 4-bit coefficient, then reuse the exact same signed 8x4
        ; truncating multiply twice. Preserve the already-accumulated bearing
        ; across the helper calls because they use HL as scratch.
        ld      a, b
        and     #0xf0
        jr      z, lbf_cross_done$
        rrca
        rrca
        rrca
        rrca                            ; A = 0..15 nibble
        bit     3, a
        jr      z, lbf_cross_sign_ready$
        or      #0xf0                   ; sign-extend -8..-1
lbf_cross_sign_ready$:
        push    hl
        ld      e, a                    ; preserve sxy while loading lx
        ld      a, (#_g_e1env_lbf_lx)
        ld      c, a
        ld      a, e
        call    lbf_mul_s8_u4_div16$
        ld      e, a                    ; first truncated product becomes slope
        ld      a, (#_g_e1env_lbf_ly)
        ld      c, a
        ld      a, e
        call    lbf_mul_s8_u4_div16$
        ld      c, a                    ; final signed cross correction
        pop     hl

        ld      e, c
        ld      d, #0
        bit     7, e
        jr      z, lbf_cross_pos$
        dec     d
lbf_cross_pos$:
        add     hl, de
lbf_cross_done$:
lbf_finalize$:

        ld      a, h
        and     #0x0f
        ld      h, a
        ld      (#_g_e1env_lbf_out), hl

        pop     hl
        pop     de
        pop     bc
        ret

; A=signed slope [-127,127], C=local [0,15].
; Return A=trunc_toward_zero(A*C/16).
;
; The generated E1M1 field overwhelmingly uses slopes in [-64,63]. Map the
; signed byte into a 128-row direct table with A+64: the table is the SAME
; 2 KiB footprint as the old magnitude-only LUT, but its hot path needs no
; abs/sign bookkeeping and returns the final signed byte directly. Rare slopes
; outside that range retain an exact shift/add fallback.
lbf_mul_s8_u4_div16$:
        ld      e, a                    ; retain original for rare fallback
        add     a, #64
        bit     7, a
        jr      nz, lbf_mul_rare$

        ; LUT is transposed as [local 0..15][biased slope 0..127].
        ; local*128 has an almost-free address form: H=local>>1 and bit7(L)
        ; carries local bit0. This replaces four 16-bit doubles plus an add.
        ld      l, a                    ; biased signed slope 0..127
        ld      a, c
        srl     a
        ld      h, a                    ; high byte of local*128
        bit     0, c
        jr      z, lbf_mul_idx_ready$
        set     7, l
lbf_mul_idx_ready$:
        ld      de, #lbf_mul_s8_u4_div16_lut$
        add     hl, de
        ld      a, (hl)
        ret

; Complete exact fallback for the tiny out-of-hot-range tail. Preserve BC:
; B holds the packed descriptor nibble across the affine calls in the caller.
lbf_mul_rare$:
        ld      a, e
        push    bc
        ld      b, #0                   ; sign flag
        bit     7, a
        jr      z, lbf_rare_mag_ready$
        neg
        inc     b
lbf_rare_mag_ready$:
        ld      e, a
        ld      d, #0
        ld      hl, #0
        ; Four multiplier bits: C is only 0..15.
        srl     c
        jr      nc, lbf_rare_b0$
        add     hl, de
lbf_rare_b0$:
        sla     e
        rl      d
        srl     c
        jr      nc, lbf_rare_b1$
        add     hl, de
lbf_rare_b1$:
        sla     e
        rl      d
        srl     c
        jr      nc, lbf_rare_b2$
        add     hl, de
lbf_rare_b2$:
        sla     e
        rl      d
        srl     c
        jr      nc, lbf_rare_b3$
        add     hl, de
lbf_rare_b3$:
        ; Positive magnitude product /16. Four shifts are irrelevant on the
        ; normal path and preserve exact truncation for the fallback.
        srl     h
        rr      l
        srl     h
        rr      l
        srl     h
        rr      l
        srl     h
        rr      l
        ld      e, l
        ld      a, b
        or      a
        ld      a, e
        jr      z, lbf_rare_sign_done$
        neg
lbf_rare_sign_done$:
        ld      e, a
        pop     bc
        ld      a, e
        ret

