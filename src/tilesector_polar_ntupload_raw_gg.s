; Mature Stage19 contract, now with the missing prerequisite restored:
; renderer/materializer already populated exact dirty bits while changing the
; authoritative g_map. VBlank DOES NOT compare map words. It consumes three
; dirty bytes per visible row and streams one [first..last] interval if needed.
_tsp_polar_nt_upload_dirty::
        push    af
        push    bc
        push    de
        push    hl
        push    ix
        push    iy

        xor     a
        ld      (#pb_row$), a
        ld      ix, #_g_polar_nt_dirty

pb_row_loop$:
        ; Consume + clear this row's 20-bit dirty state.
        ld      a, 0 (ix)
        ld      (#pb_d0$), a
        ld      0 (ix), #0
        ld      d, a
        ld      a, 1 (ix)
        ld      (#pb_d1$), a
        ld      1 (ix), #0
        or      d
        ld      d, a
        ld      a, 2 (ix)
        and     #0x0F
        ld      (#pb_d2$), a
        ld      2 (ix), #0
        or      d
        jp      z, pb_next_row$

        ; First dirty column.
        ld      a, (#pb_d0$)
        or      a
        jr      nz, pb_first_g0$
        ld      a, (#pb_d1$)
        or      a
        jr      nz, pb_first_g1$
        ld      a, (#pb_d2$)
        call    pb_first_bit$
        add     a, #16
        jr      pb_first_ready$
pb_first_g1$:
        call    pb_first_bit$
        add     a, #8
        jr      pb_first_ready$
pb_first_g0$:
        call    pb_first_bit$
pb_first_ready$:
        ld      (#pb_first$), a

        ; Last dirty column.
        ld      a, (#pb_d2$)
        or      a
        jr      z, pb_last_not_g2$
        call    pb_last_bit$
        add     a, #16
        jr      pb_last_ready$
pb_last_not_g2$:
        ld      a, (#pb_d1$)
        or      a
        jr      z, pb_last_g0$
        call    pb_last_bit$
        add     a, #8
        jr      pb_last_ready$
pb_last_g0$:
        ld      a, (#pb_d0$)
        call    pb_last_bit$
pb_last_ready$:
        ld      (#pb_last$), a

        ; words = last-first+1.
        ld      c, a
        ld      a, (#pb_first$)
        ld      e, a
        ld      a, c
        sub     e
        inc     a
        ld      (#pb_words$), a

        ; HL = g_map row base + first*2.
        ld      a, (#pb_row$)
        add     a, a
        ld      e, a
        ld      d, #0
        ld      hl, #pb_map_rows$
        add     hl, de
        ld      e, (hl)
        inc     hl
        ld      d, (hl)
        ex      de, hl
        ld      a, (#pb_first$)
        add     a, a
        ld      e, a
        ld      d, #0
        add     hl, de

        ; DE = visible VDP row base + first*2.
        push    hl
        ld      a, (#pb_row$)
        add     a, a
        ld      e, a
        ld      d, #0
        ld      hl, #pb_vdp_rows$
        add     hl, de
        ld      e, (hl)
        inc     hl
        ld      d, (hl)
        ld      a, (#pb_first$)
        add     a, a
        ld      c, a
        ld      b, #0
        ex      de, hl
        add     hl, bc
        ex      de, hl
        pop     hl

        ; One hardware transaction for the complete interval.
        di
        ld      a, e
        out     (#0xBF), a
        ld      a, d
        or      #0x40
        out     (#0xBF), a
        ld      c, #0xBE
        ld      a, (#pb_words$)
        add     a, a
        ld      b, a
        otir
        ei

pb_next_row$:
        inc     ix
        inc     ix
        inc     ix
        ld      a, (#pb_row$)
        inc     a
        ld      (#pb_row$), a
        cp      #18
        jp      c, pb_row_loop$

        pop     iy
        pop     ix
        pop     hl
        pop     de
        pop     bc
        pop     af
        ret

pb_first_bit$:
        ld      l, a
        ld      h, #0
        ld      de, #pb_first_lut$
        add     hl, de
        ld      a, (hl)
        ret

pb_last_bit$:
        ld      l, a
        ld      h, #0
        ld      de, #pb_last_lut$
        add     hl, de
        ld      a, (hl)
        ret

