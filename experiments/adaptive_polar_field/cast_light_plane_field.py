#!/usr/bin/env python3
"""Emit the compact receiver-owned Polar cast-plane field.

Unlike the endpoint-reference bake in cast_light_field.py, this representation
stores no projected cast endpoints for floor lighting. A vertical shadow plane
is mathematically the same screen-depth plane used by an arbitrary straight
wall. Its intersection with a horizontal receiver floor is therefore the
bottom edge of a synthetic/virtual wall:

    invDepth(x) = affine across screen x
    floorY(x)   = horizon + floorHeightScale * invDepth(x)

The ordinary geometry pass supplies receiver-surface ownership. The cast line
may safely extend beyond its physical endpoints because lighting writes are
accepted only on floor cells owned by the cast's receiver surface. The static
far-wall hit remains a tiny Q8 fraction on the receiver wall for the later
vertical wall-light split.

Per camera grid cell we therefore need only one four-bit active-cast mask.
"""
from __future__ import annotations

import argparse
import pathlib
from typing import Sequence

import cast_light_field as topo
import local_projection_field_poc as lp

GRID_W, GRID_H = lp.GRID_W, lp.GRID_H
ROOT = pathlib.Path(__file__).resolve().parents[2]


def c_u8(name: str, data: Sequence[int], cols: int = 16) -> str:
    out=[f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0,len(data),cols): out.append("    "+", ".join(str(int(v)&255) for v in data[i:i+cols])+",")
    out.append("};"); return "\n".join(out)


def c_i8(name: str, data: Sequence[int], cols: int = 16) -> str:
    out=[f"static const int8_t {name}[{len(data)}] = {{"]
    for i in range(0,len(data),cols): out.append("    "+", ".join(str(int(v)) for v in data[i:i+cols])+",")
    out.append("};"); return "\n".join(out)


def shr0(v:int,n:int)->int: return v>>n if v>=0 else -((-v)>>n)

def round_div_signed(n:int,d:int)->int: return (n+d//2)//d if n>=0 else -(((-n)+d//2)//d)


def active_mask(d:lp.D,gx:int,gy:int)->int:
    # Correctness-first: all four cast planes are available from any non-empty
    # Polar cell. This is one byte per cell; topology culling can be added only
    # after dense camera/yaw validation proves it cannot suppress a visible run.
    return 0x0F if d.grid[gy*GRID_W+gx] != 255 else 0x00


def emit(outdir:pathlib.Path,rows_per_bank:int)->None:
    d=lp.load(); casts=topo.derive_casts(d); outdir.mkdir(parents=True,exist_ok=True)
    banks=(GRID_H+rows_per_bank-1)//rows_per_bank
    payload_total=0
    for bank in range(banks):
        y0=bank*rows_per_bank;y1=min(GRID_H,y0+rows_per_bank)
        masks=[]
        for gy in range(y0,y1):
            for gx in range(GRID_W): masks.append(active_mask(d,gx,gy))
        payload_total+=len(masks)
        src=f'''/* GENERATED by cast_light_plane_field.py. */
#include <stdint.h>
#include <gbdk/platform.h>
#pragma bank 255
BANKREF(tilesector_polar_castmask_bank{bank})

{c_u8("k_cast_mask",masks)}

uint8_t tsp_polar_castmask_load_bank{bank}(uint8_t cell) BANKED {{ return k_cast_mask[cell]; }}
'''
        (outdir/f'tilesector_polar_castmask_bank{bank}.c').write_text(src)
        print(f'CAST_MASK_BANK bank={bank} rows={y0}-{y1-1} bytes={len(masks)}')

    text='\n'.join(p.read_text() for p in sorted((ROOT/'src/generated').glob('tilesector_polar_data_part*.inc')))
    sin=lp.arr(text,'k_tspf_sin_q7')
    nf_rows=[];sf_rows=[]
    for c in casts:
        nf=[];sf=[]
        for yaw in range(256):
            sn=sin[yaw];cs=sin[(yaw+64)&255]
            f=shr0(c.nx_q5*cs+c.ny_q5*sn,5)
            side=shr0(-c.nx_q5*sn+c.ny_q5*cs,5)
            nf.append(max(-127,min(127,f)))
            sf.append(max(-127,min(127,round_div_signed(side*4,5))))
        nf_rows.append(nf);sf_rows.append(sf)

    def rows(name,rs):
        o=[f'static const int8_t {name}[{len(rs)}][256] = {{']
        for r in rs:
            o.append('    {')
            for i in range(0,256,16):o.append('        '+', '.join(str(v) for v in r[i:i+16])+',')
            o.append('    },')
        o.append('};');return '\n'.join(o)

    hdr=[
      '/* GENERATED compact receiver-owned Polar cast-light metadata. */',
      '#ifndef TILESECTOR_POLAR_CAST_PLANE_META_H',
      '#define TILESECTOR_POLAR_CAST_PLANE_META_H',
      '#include <stdint.h>', '#include <gbdk/platform.h>',
      f'#define TSPF_CAST_COUNT {len(casts)}u',
      f'#define TSPF_CAST_MASK_BANK_COUNT {banks}u',
      f'#define TSPF_CAST_MASK_ROWS_PER_BANK {rows_per_bank}u',
      f'#define TSPF_CAST_SURFACE_ROOM_A {topo.SURFACE_ROOM_A}u',
      f'#define TSPF_CAST_SURFACE_ROOM_B {topo.SURFACE_ROOM_B}u',
      f'#define TSPF_CAST_SIDE_RIGHT {topo.SIDE_RIGHT}u',
      f'#define TSPF_CAST_SIDE_LEFT {topo.SIDE_LEFT}u',
      c_u8('k_tspf_cast_caster',[c.caster_vid for c in casts]),
      c_u8('k_tspf_cast_receiver_sid',[c.receiver_sid for c in casts]),
      c_u8('k_tspf_cast_receiver_surface',[c.receiver_surface for c in casts]),
      c_u8('k_tspf_cast_floor_z',[c.floor_z for c in casts]),
      c_u8('k_tspf_cast_shadow_side',[c.shadow_side for c in casts]),
      c_u8('k_tspf_cast_split_u_q8',[c.split_u_q8 for c in casts]),
      c_i8('k_tspf_cast_nx_q5',[c.nx_q5 for c in casts]),
      c_i8('k_tspf_cast_ny_q5',[c.ny_q5 for c in casts]),
    ]
    for b in range(banks):hdr.append(f'uint8_t tsp_polar_castmask_load_bank{b}(uint8_t cell) BANKED;')
    hdr.append('void tsp_polar_castplane_load(uint8_t yaw,int8_t *nf,int8_t *sf) BANKED;')
    hdr.append('#endif')
    (outdir/'tilesector_polar_cast_plane_meta.h').write_text('\n\n'.join(hdr)+'\n')

    src=f'''/* GENERATED by cast_light_plane_field.py. */
#include <stdint.h>
#include <gbdk/platform.h>
#include "tilesector_polar_cast_plane_meta.h"
#pragma bank 255
BANKREF(tilesector_polar_castplane_compact)

{rows('k_cast_nf_q7',nf_rows)}

{rows('k_cast_stepfac_q4',sf_rows)}

void tsp_polar_castplane_load(uint8_t yaw,int8_t *nf,int8_t *sf) BANKED {{
    uint8_t c;for(c=0u;c<TSPF_CAST_COUNT;++c){{nf[c]=k_cast_nf_q7[c][yaw];sf[c]=k_cast_stepfac_q4[c][yaw];}}
}}
'''
    (outdir/'tilesector_polar_castplane.c').write_text(src)

    coeff_bytes=len(casts)*256*2
    print('CAST_CHAIN_AUDIT=PASS')
    print(f'CAST_PLANE_GRID_BAKE=PASS cells={GRID_W*GRID_H} mask_payload={payload_total} plane_coeff={coeff_bytes} core_data={payload_total+coeff_bytes}')
    print('CAST_FLOOR_ENDPOINT_BYTES=0')
    print('CAST_FLOOR_RUNTIME_MODEL=VIRTUAL_WALL_BOTTOM_EDGE_PLUS_RECEIVER_OWNER')
    for i,c in enumerate(casts):
        print(f'CAST {i}: v{c.caster_vid} plane_n_q5={c.nx_q5},{c.ny_q5} receiver_surface={c.receiver_surface} receiver_wall={c.receiver_sid} wall_split_u_q8={c.split_u_q8}')


def main()->None:
    ap=argparse.ArgumentParser();ap.add_argument('--emit-dir',required=True);ap.add_argument('--rows-per-bank',type=int,default=4)
    a=ap.parse_args();emit(pathlib.Path(a.emit_dir),a.rows_per_bank)

if __name__=='__main__':main()
