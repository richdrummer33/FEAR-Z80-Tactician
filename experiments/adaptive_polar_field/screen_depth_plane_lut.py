#!/usr/bin/env python3
"""Generate compact Polar screen-depth plane coefficients.

For a straight wall, inverse camera-space depth is linear in screen tan(x):
    inv_z = inv_perp * (n_forward + n_side * tan(rel))

The GG materializer already consumes a Q6 start + Q6 step across coarse
8-pixel columns.  We therefore precompute, for each UNIQUE authored wall
normal and yaw:
  nf_q7       = camera-forward normal component
  stepfac_q4  ~= 0.8 * camera-side normal component

Then runtime needs two small products per run:
  center_inv_q6 = invd * nf_q7 / 2
  col_step_q6   = invd * stepfac_q4 / 16

No per-endpoint sin/cos/dot/sec path is required.  The table is keyed by
normal-class<<8 | yaw, so seven normal families cost only 3584 coefficient
bytes plus the 17-byte segment->class map.
"""
from __future__ import annotations
import argparse,pathlib,re

ROOT=pathlib.Path(__file__).resolve().parents[2]
GEN=ROOT/"src"/"generated"

def arr(text,name):
    m=re.search(r"static\s+const\s+[^;=]+?\b"+re.escape(name)+r"\s*\[[^\]]+\]\s*=\s*\{(.*?)\};",text,re.S)
    if not m: raise SystemExit("missing generated array "+name)
    return [int(x,0) for x in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+",m.group(1))]

def shr0(v,n):
    return v>>n if v>=0 else -((-v)>>n)

def round_div_signed(n,d):
    return (n+d//2)//d if n>=0 else -(((-n)+d//2)//d)

def emit(outdir):
    text="\n".join(p.read_text() for p in sorted(GEN.glob("tilesector_polar_data_part*.inc")))
    nx=arr(text,"k_tspf_nx_q5"); ny=arr(text,"k_tspf_ny_q5"); sin=arr(text,"k_tspf_sin_q7")
    normals=[]; cls=[]
    for pair in zip(nx,ny):
        if pair not in normals:normals.append(pair)
        cls.append(normals.index(pair))

    nf=[]; sf=[]
    for cx,cy in normals:
      row_nf=[]; row_sf=[]
      for yaw in range(256):
        sn=sin[yaw]; cs=sin[(yaw+64)&255]
        f=shr0(cx*cs+cy*sn,5)
        side=shr0(-cx*sn+cy*cs,5)
        f=max(-127,min(127,f)); side=max(-127,min(127,side))
        row_nf.append(f)
        # Desired Q6 inverse-depth delta per 8-pixel coarse column is
        # invd*side/20. Encode side*4/5 so runtime is invd*sf >> 4.
        row_sf.append(max(-127,min(127,round_div_signed(side*4,5))))
      nf.append(row_nf); sf.append(row_sf)

    def emit_u8(name,data,cols=17):
        out=[f"static const uint8_t {name}[{len(data)}] = {{"]
        for i in range(0,len(data),cols):
            out.append("    "+", ".join(str(v) for v in data[i:i+cols])+",")
        out.append("};")
        return "\n".join(out)

    def emit_i8_rows(name,rows):
        out=[f"static const int8_t {name}[{len(rows)}][256] = {{"]
        for row in rows:
            out.append("    {")
            for i in range(0,256,16):
                out.append("        "+", ".join(str(v) for v in row[i:i+16])+",")
            out.append("    },")
        out.append("};")
        return "\n".join(out)

    outdir=pathlib.Path(outdir);outdir.mkdir(parents=True,exist_ok=True)
    hdr=f"""/* GENERATED by screen_depth_plane_lut.py. */
#ifndef TILESECTOR_POLAR_DEPTH_PLANE_LUT_H
#define TILESECTOR_POLAR_DEPTH_PLANE_LUT_H
#include <stdint.h>
#include <gbdk/platform.h>
#define TSPF_DEPTH_NORMAL_CLASS_COUNT {len(normals)}u
{emit_u8("k_tspf_depth_normal_class",cls)}
void tsp_polar_depthplane_load(uint8_t yaw, int8_t *nf, int8_t *sf) BANKED;
#endif
"""
    src=f"""/* GENERATED by screen_depth_plane_lut.py. */
#include <stdint.h>
#include <gbdk/platform.h>
#pragma bank 255
BANKREF(tilesector_polar_depthplane)

{emit_i8_rows("k_depth_nf_q7",nf)}

{emit_i8_rows("k_depth_stepfac_q4",sf)}

void tsp_polar_depthplane_load(uint8_t yaw, int8_t *nf, int8_t *sf) BANKED {{
    uint8_t c;
    for(c=0u;c<TSPF_DEPTH_NORMAL_CLASS_COUNT;++c){{
        nf[c]=k_depth_nf_q7[c][yaw];
        sf[c]=k_depth_stepfac_q4[c][yaw];
    }}
}}
"""
    # Source needs the generated header for class-count.
    src=src.replace('#include <gbdk/platform.h>','#include <gbdk/platform.h>\n#include "tilesector_polar_depthplane_lut.h"')
    (outdir/"tilesector_polar_depthplane_lut.h").write_text(hdr)
    (outdir/"tilesector_polar_depthplane.c").write_text(src)
    total=len(cls)+sum(len(r) for r in nf)+sum(len(r) for r in sf)
    print(f"depth-plane LUT: unique normals={len(normals)} coefficient pairs={len(normals)*256} data-bytes={total}")

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--emit-dir",required=True)
    a=ap.parse_args();emit(a.emit_dir)

if __name__=="__main__":main()
